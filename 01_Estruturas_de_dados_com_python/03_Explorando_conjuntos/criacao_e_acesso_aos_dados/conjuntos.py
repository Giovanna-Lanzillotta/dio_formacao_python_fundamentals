# CONJUNTOS

numeros = set([1, 2, 3, 1, 3, 4])
print(numeros) # {1, 2, 3, 4}


fruta = set("abacaxi")
print(fruta) # {'x', 'i', 'c', 'a', 'b'}


carros = set(("palio", "gol", "celta", "palio"))
print(carros) # {'palio', 'celta', 'gol'}


notas = set([10, 3.5, 7.8, 9.3, 7.87, 7.81, 10 ])
print(notas) # {3.5, 7.87, 7.8, 9.3, 10, 7.81}


linguagens = {"python", "java", "python"}
print(linguagens) # {'python', 'java'}
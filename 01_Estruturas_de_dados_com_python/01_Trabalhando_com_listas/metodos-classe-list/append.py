# Métodos da classe list - [].append

lista = []

lista.append(1)
lista.append("python")
lista.append([40,30,20])

print(lista) #[1, "python", [40,30,20]]


frutas = ["uva", "banana", "abacaxi"]

print(frutas)  # ['uva', 'banana', 'abacaxi']

frutas.append("laranja")
frutas.append("morango")

print(frutas) # ['uva', 'banana', 'abacaxi', 'laranja', 'morango']
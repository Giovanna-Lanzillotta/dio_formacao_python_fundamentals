# exemplo
#string: conta o numero de caracteres
texto = len("python")
print(texto) # 6

#lista: onta quantos elementos tem
lista = len([10, 20, 30])
print(lista) # 3

#dicionário: conta pares de chave-valor
dic = len({"nome": "Alice", "idade": 30}) # 2
print(dic)